#!/usr/bin/env python3
"""Heart-tissue-beam benchmark (Land et al. 2015, problem 1): manuscript Fig 13.

Replaces ``dz.gnuplot`` (kept next to this file) with the shared manuscript
style.  Data selection and transformations are those of the gnuplot script:

* simulation curve: ``beam.summary.txt`` columns 2 (cell size [mm]) and
  4 (D_z [m]); plotted quantity z_tip = 1 mm + 1e3 * D_z, i.e. the deformed
  z-coordinate of the material point (10, 0.5, 1) mm; mesh 1 is omitted
  (``every ::1``), as in the existing figure;
* reference lines: landMin, landMedian, landMax from
  ``reference_data/land_problem1_reference_stats.gp`` (minimum, median and
  maximum of ALL 23 supplied Land et al. (2015) deformed tip z values, the
  same monitored quantity; generated by extract_land_problem1_reference.py).

Output: land_problem1_m3_verticalDisplacement_vs_cellSize.pdf (the "m3" in
the file name is the old one-based index; the operator is coupled m = 2).
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path


def _load_paper_style():
    candidates = [Path(os.environ["JFNK_PAPER_STYLE_DIR"])] if "JFNK_PAPER_STYLE_DIR" in os.environ else []
    candidates += [parent / "plotStyle" for parent in Path(__file__).resolve().parents]
    for directory in candidates:
        if (directory / "paper_figure_style.py").is_file():
            sys.path.insert(0, str(directory))
            import paper_figure_style  # noqa: E402

            return paper_figure_style
    raise SystemExit("ERROR: paper_figure_style.py not found (set JFNK_PAPER_STYLE_DIR)")


pfs = _load_paper_style()
from matplotlib.ticker import FixedLocator, FuncFormatter, MultipleLocator, NullLocator  # noqa: E402

OUTPUT_NAME = "land_problem1_m3_verticalDisplacement_vs_cellSize.pdf"
INITIAL_TIP_Z_MM = 1.0
WIDTH_FRACTION = 0.70            # \includegraphics[width=0.70\linewidth]
ASPECT = 0.62
X_TICKS = (0.03125, 0.0625, 0.125, 0.25, 0.5)
X_LIM = (0.026, 0.60)
Y_LIM = (3.4, 4.25)
SIMULATION_LABEL = "Present work, coupled $m = 2$"


def read_summary(path: Path) -> list[tuple[int, float, float]]:
    rows = []
    for line in path.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        f = line.split()
        rows.append((int(f[0]), float(f[1]), float(f[3])))
    if not rows:
        raise ValueError(f"no data in {path}")
    return rows


def read_stats(path: Path) -> dict[str, float]:
    stats = {}
    for line in path.read_text().splitlines():
        m = re.match(r"\s*(landN|landMin|landMedian|landMax)\s*=\s*([-+0-9.eE]+)", line)
        if m:
            stats[m.group(1)] = float(m.group(2))
    for key in ("landMin", "landMedian", "landMax"):
        if key not in stats:
            raise ValueError(f"{key} missing from {path}")
    return stats


def main() -> None:
    script_dir = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--summary", type=Path, required=True,
                        help="beam.summary.txt written by ../Allrun (runs/beam.summary.txt)")
    parser.add_argument("--stats", type=Path,
                        default=script_dir.parent / "referenceData" / "land_problem1_reference_stats.gp",
                        help="Land et al. (2015) reference statistics (default: ../referenceData)")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--dump-series", type=Path)
    args = parser.parse_args()

    try:
        rows = read_summary(args.summary)
        stats = read_stats(args.stats)
    except (OSError, ValueError, IndexError) as error:
        raise SystemExit(f"ERROR: {error}") from error
    # Mesh 1 (10 cells) is not part of the figure.  The original gnuplot
    # script dropped it with `every ::1` (first data line); here it is dropped
    # by its mesh index, so that a summary that starts at mesh 2 keeps mesh 2.
    plotted = sorted((r for r in rows if r[0] != 1), key=lambda r: r[0])
    if not plotted:
        raise SystemExit(f"ERROR: {args.summary} has no mesh level above 1; nothing to plot")
    levels = [r[0] for r in plotted]
    if len(set(levels)) != len(levels):
        raise SystemExit(f"ERROR: repeated mesh levels in {args.summary}: {levels}")
    x = [r[1] for r in plotted]
    y = [INITIAL_TIP_Z_MM + 1e3 * r[2] for r in plotted]

    fig, ax = pfs.new_figure(WIDTH_FRACTION, ASPECT)
    ax.set_xscale("log")
    pfs.style_axes(ax)
    name = OUTPUT_NAME
    for key in ("max", "median", "min"):
        value = stats[{"max": "landMax", "median": "landMedian", "min": "landMin"}[key]]
        style = pfs.LAND_STAT_STYLES[key]
        ax.axhline(value, **style.kwargs(marker="None"))
        pfs.record_series(name, f"reference:{key}", [X_LIM[0], X_LIM[1]], [value, value])
    ax.plot(x, y, **pfs.line_kwargs("coupled_m2", label=SIMULATION_LABEL))
    pfs.record_series(name, "simulation:coupled_m2", x, y)

    ax.set_xlim(X_LIM)
    ax.set_ylim(Y_LIM)
    ax.xaxis.set_major_locator(FixedLocator(X_TICKS))
    ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:g}"))
    ax.xaxis.set_minor_locator(NullLocator())
    ax.yaxis.set_major_locator(MultipleLocator(0.1))
    ax.yaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:.1f}"))
    ax.set_xlabel("Cell size [mm]")
    ax.set_ylabel(r"Deformed tip coordinate $z_{\mathrm{tip}}$ [mm]")
    handles, labels = ax.get_legend_handles_labels()
    order = [labels.index(SIMULATION_LABEL)] + [i for i, l in enumerate(labels) if l != SIMULATION_LABEL]
    leg = pfs.legend(ax, [handles[i] for i in order], [labels[i] for i in order], loc="lower left")
    pfs.assert_legend_clear(fig, ax, leg, name)
    pfs.record_axes(name, ax)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    pfs.save(fig, args.output_dir / name, title="Heart tissue beam: deformed tip coordinate vs cell size")
    if args.dump_series is not None:
        pfs.write_records(args.dump_series)
    print(f"Wrote {args.output_dir / name}")


if __name__ == "__main__":
    main()
