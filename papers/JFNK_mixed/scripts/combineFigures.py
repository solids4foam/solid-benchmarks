#!/usr/bin/env python3
"""Assemble the collected benchmark figures into a single PDF.

The figures are grouped by test case. Each group is introduced by a heading
naming the test case, and every figure carries a short caption underneath.

Two renderers are supported. The first uses pdflatex, which embeds the figure
PDFs directly and keeps them vector. If pdflatex is unavailable or fails, the
figures are rasterised with Ghostscript and laid out with ReportLab instead.

Input is the tab-separated manifest written by the top-level Allrun:

    index <TAB> heading <TAB> caption <TAB> path-relative-to-root
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path


@dataclass
class Figure:
    path: Path
    caption: str


@dataclass
class Group:
    heading: str
    figures: list[Figure] = field(default_factory=list)


def read_manifest(manifest: Path, root: Path) -> list[Group]:
    """Return the manifest as ordered groups, keeping only existing files."""

    groups: dict[str, Group] = {}
    order: list[str] = []

    for line_number, line in enumerate(manifest.read_text().splitlines(), 1):
        if not line.strip():
            continue

        fields = line.split("\t")
        if len(fields) != 4:
            raise SystemExit(f"{manifest}:{line_number}: expected 4 fields, got {len(fields)}")

        index, heading, caption, relative = fields
        path = (root / relative).resolve()
        if not path.is_file():
            print(f"WARNING: missing figure, skipping: {relative}", file=sys.stderr)
            continue

        key = f"{index}\t{heading}"
        if key not in groups:
            groups[key] = Group(heading)
            order.append(key)
        groups[key].figures.append(Figure(path, caption))

    return [groups[key] for key in order]


# ---------------------------------------------------------------------------
# pdflatex renderer
# ---------------------------------------------------------------------------

LATEX_SPECIALS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def latex_escape(text: str) -> str:
    return "".join(LATEX_SPECIALS.get(character, character) for character in text)


def build_latex_source(groups: list[Group], title: str, subtitle: str) -> str:
    """Write a LaTeX document with one heading per test case and its figures.

    fancyhdr is loaded only when it is installed, so that the heading of the
    current test case is repeated on continuation pages where it is available
    without making the whole document depend on it.
    """

    lines = [
        r"\documentclass[11pt]{article}",
        r"\usepackage[a4paper,margin=18mm,includeheadfoot]{geometry}",
        r"\usepackage{graphicx}",
        r"\usepackage[T1]{fontenc}",
        r"\usepackage{parskip}",
        r"\setcounter{secnumdepth}{0}",
        # A landscape plot is capped so that two fit on a page; a portrait plot
        # such as the stacked ventricle mid-line panels is given most of the
        # page instead, so that it is not shrunk to fit a landscape budget.
        r"\newsavebox{\figbox}",
        r"\newcommand{\autofig}[1]{%",
        r"  \sbox{\figbox}{\includegraphics{#1}}%",
        r"  \ifdim\wd\figbox>\ht\figbox",
        r"    \includegraphics[width=\linewidth,height=0.40\textheight,keepaspectratio]{#1}%",
        r"  \else",
        r"    \includegraphics[width=\linewidth,height=0.78\textheight,keepaspectratio]{#1}%",
        r"  \fi",
        r"}",
        r"\IfFileExists{fancyhdr.sty}{%",
        r"  \usepackage{fancyhdr}",
        r"  \pagestyle{fancy}",
        r"  \fancyhf{}",
        r"  \fancyhead[L]{\small\itshape\nouppercase{\leftmark}}",
        r"  \fancyfoot[C]{\small\thepage}",
        r"  \renewcommand{\headrulewidth}{0.4pt}",
        r"}{\pagestyle{plain}}",
        r"\begin{document}",
        r"\thispagestyle{empty}",
        r"\begin{center}",
        r"\vspace*{40mm}",
        r"{\LARGE\bfseries " + latex_escape(title) + r"}\\[6mm]",
        r"{\large " + latex_escape(subtitle) + r"}\\[3mm]",
        r"{\small Generated by \texttt{./Allrun} in the \texttt{JFNK\_mixed} directory}",
        r"\end{center}",
        r"\vspace{14mm}",
        r"\tableofcontents",
        r"\clearpage",
    ]

    for group in groups:
        heading = latex_escape(group.heading)
        lines.append(r"\section{" + heading + "}")
        lines.append(r"\markboth{" + heading + "}{" + heading + "}")

        for figure in group.figures:
            lines.append(r"\begin{center}")
            lines.append(r"\autofig{" + figure.path.as_posix() + "}")
            if figure.caption:
                lines.append(r"\\[2mm]{\small " + latex_escape(figure.caption) + "}")
            lines.append(r"\end{center}")
            lines.append(r"\vspace{6mm}")

        lines.append(r"\clearpage")

    lines.append(r"\end{document}")
    return "\n".join(lines) + "\n"


def render_with_pdflatex(groups: list[Group], output: Path, title: str, subtitle: str) -> bool:
    pdflatex = shutil.which("pdflatex")
    if pdflatex is None:
        return False

    source = build_latex_source(groups, title, subtitle)

    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        tex = work / "figures.tex"
        tex.write_text(source)

        # Two passes so that the table of contents is populated.
        for _ in range(2):
            result = subprocess.run(
                [pdflatex, "-interaction=nonstopmode", "-halt-on-error", tex.name],
                cwd=work,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
            )
            if result.returncode != 0:
                print("pdflatex failed; falling back to the raster renderer.", file=sys.stderr)
                print(result.stdout[-2000:], file=sys.stderr)
                return False

        produced = work / "figures.pdf"
        if not produced.is_file():
            return False

        output.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(produced, output)

    return True


# ---------------------------------------------------------------------------
# Ghostscript and ReportLab renderer
# ---------------------------------------------------------------------------

def rasterise(source: Path, destination: Path, resolution: int = 200) -> bool:
    ghostscript = shutil.which("gs")
    if ghostscript is None:
        return False

    result = subprocess.run(
        [
            ghostscript,
            "-q",
            "-dBATCH",
            "-dNOPAUSE",
            "-dSAFER",
            "-sDEVICE=png16m",
            f"-r{resolution}",
            "-dFirstPage=1",
            "-dLastPage=1",
            f"-sOutputFile={destination}",
            str(source),
        ],
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )

    if result.returncode != 0:
        print(f"Ghostscript failed for {source.name}:\n{result.stdout}", file=sys.stderr)
        return False

    return destination.is_file()


def render_with_reportlab(groups: list[Group], output: Path, title: str, subtitle: str) -> bool:
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.utils import ImageReader
        from reportlab.pdfgen import canvas
    except ImportError:
        print("ReportLab is not installed; cannot build the combined PDF.", file=sys.stderr)
        return False

    page_width, page_height = A4
    margin = 18 * 72 / 25.4

    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        output.parent.mkdir(parents=True, exist_ok=True)
        pdf = canvas.Canvas(str(output), pagesize=A4)
        pdf.setTitle(title)

        # Title page
        pdf.setFont("Helvetica-Bold", 18)
        pdf.drawCentredString(page_width / 2, page_height * 0.6, title)
        pdf.setFont("Helvetica", 13)
        pdf.drawCentredString(page_width / 2, page_height * 0.6 - 28, subtitle)
        pdf.setFont("Helvetica", 9)
        pdf.drawCentredString(page_width / 2, page_height * 0.6 - 48, "Generated by ./Allrun")
        pdf.showPage()

        counter = 0
        for group in groups:
            for figure in group.figures:
                counter += 1
                png = work / f"figure{counter:03d}.png"
                if not rasterise(figure.path, png):
                    continue

                image = ImageReader(str(png))
                image_width, image_height = image.getSize()

                cursor = page_height - margin

                pdf.setFont("Helvetica-Bold", 13)
                pdf.drawString(margin, cursor - 13, group.heading)
                cursor -= 30

                caption_height = 16 if figure.caption else 0
                available_width = page_width - 2 * margin
                available_height = cursor - margin - caption_height
                scale = min(
                    available_width / image_width,
                    available_height / image_height,
                )
                width = image_width * scale
                height = image_height * scale

                pdf.drawImage(
                    image,
                    (page_width - width) / 2,
                    cursor - height,
                    width=width,
                    height=height,
                )

                if figure.caption:
                    pdf.setFont("Helvetica", 9)
                    pdf.drawCentredString(
                        page_width / 2, cursor - height - 12, figure.caption
                    )

                pdf.showPage()

        pdf.save()

    return output.is_file()


# ---------------------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--title", default="Benchmark figures")
    parser.add_argument("--subtitle", default="")
    parser.add_argument(
        "--renderer",
        choices=("auto", "pdflatex", "raster"),
        default="auto",
        help="Force a renderer instead of trying pdflatex first (default: auto).",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()

    if not args.manifest.is_file():
        raise SystemExit(f"ERROR: manifest not found: {args.manifest}")

    groups = read_manifest(args.manifest, args.root.resolve())
    if not groups:
        raise SystemExit("ERROR: the manifest lists no existing figures")

    total = sum(len(group.figures) for group in groups)
    print(f"Combining {total} figure(s) from {len(groups)} test case(s)")

    if args.renderer in ("auto", "pdflatex"):
        if render_with_pdflatex(groups, args.output, args.title, args.subtitle):
            print(f"Wrote {args.output} (pdflatex)")
            return 0
        if args.renderer == "pdflatex":
            raise SystemExit("ERROR: the pdflatex renderer failed")

    if render_with_reportlab(groups, args.output, args.title, args.subtitle):
        print(f"Wrote {args.output} (Ghostscript and ReportLab)")
        return 0

    raise SystemExit(
        "ERROR: neither pdflatex nor Ghostscript with ReportLab could build the PDF"
    )


if __name__ == "__main__":
    sys.exit(main())
